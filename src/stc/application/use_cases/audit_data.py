"""Render the leakage/duplication audit as JSON and Markdown."""

from __future__ import annotations

import json
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import cast

from stc.application.use_cases.prepare_data import DatasetInspection, PrepareDataPipeline
from stc.domain.leakage import DropReason
from stc.domain.splits import Split

_DATASET_NAME = "Amazon MASSIVE 1.0 es-ES"


@dataclass(frozen=True, slots=True)
class DataAuditPaths:
    """Where the audit report was written."""

    json_path: Path
    markdown_path: Path


def build_audit_payload(inspection: DatasetInspection) -> dict[str, object]:
    """Build the committed ``data_audit.json`` payload."""
    audit = inspection.audit
    drops = Counter(row.reason.value for row in inspection.cleaned.dropped)
    dropped_ids: dict[str, list[str]] = {reason.value: [] for reason in DropReason}
    for row in inspection.cleaned.dropped:
        dropped_ids[row.reason.value].append(row.id)

    return {
        "schema_version": 1,
        "dataset": _DATASET_NAME,
        "dataset_id": "massive",
        "dataset_version": "1.0",
        "tarball_sha256": inspection.ref.sha256,
        "stc_version": inspection.stc_version,
        "raw_counts": {split.value: len(rows) for split, rows in inspection.splits.items()},
        "processed_counts": {
            "train": len(inspection.cleaned.rows),
            "dev": len(inspection.splits[Split.DEV]),
            "test": len(inspection.splits[Split.TEST]),
        },
        "dev_test_overlap_texts": audit.dev_test_overlap_texts,
        "dev_rows_in_train": audit.dev_rows_in_train,
        "dev_rows_in_train_label_conflict": audit.dev_rows_in_train_label_conflict,
        "test_rows_in_train": audit.test_rows_in_train,
        "test_rows_in_train_label_conflict": audit.test_rows_in_train_label_conflict,
        "train_duplicate_groups": audit.train_duplicate_groups,
        "train_duplicate_excess_rows": audit.train_duplicate_excess_rows,
        "label_conflict_groups": audit.train_label_conflict_groups,
        "dev_duplicate_groups": audit.dev_duplicate_groups,
        "dev_duplicate_excess_rows": audit.dev_duplicate_excess_rows,
        "test_duplicate_groups": audit.test_duplicate_groups,
        "test_duplicate_excess_rows": audit.test_duplicate_excess_rows,
        "worker_partition_overlap": {
            "workers_in_multiple_partitions": (
                audit.worker_partition_overlap.workers_in_multiple_partitions
            ),
            "total_workers": audit.worker_partition_overlap.total_workers,
        },
        "drops": {reason.value: drops.get(reason.value, 0) for reason in DropReason},
        "dropped_ids_by_reason": dropped_ids,
        "train_after": len(inspection.cleaned.rows),
    }


def render_markdown(payload: dict[str, object]) -> str:
    """Render the human-readable companion report."""
    raw_counts = cast(dict[str, int], payload["raw_counts"])
    processed_counts = cast(dict[str, int], payload["processed_counts"])
    drops = cast(dict[str, int], payload["drops"])
    workers = cast(dict[str, int], payload["worker_partition_overlap"])
    lines = [
        "# Data audit",
        "",
        "Generated by `uv run stc data audit --out reports` from the pinned "
        "Amazon MASSIVE 1.0 `es-ES` archive.",
        "",
        f"- Source sha256: `{payload['tarball_sha256']}`",
        f"- Dataset: {payload['dataset']}",
        f"- Drops applied to train only: {sum(drops.values())}",
        "",
        "## Row counts",
        "",
        "| split | raw rows | processed rows |",
        "|---|---|---|",
    ]
    for split in ("train", "dev", "test"):
        lines.append(f"| {split} | {raw_counts[split]} | {processed_counts[split]} |")
    lines.extend(
        [
            "",
            "## Leakage and duplication",
            "",
            f"- Dev/test normalised overlap: {payload['dev_test_overlap_texts']}",
            f"- Dev rows also in train: {payload['dev_rows_in_train']} "
            f"({payload['dev_rows_in_train_label_conflict']} label-conflicting)",
            f"- Test rows also in train: {payload['test_rows_in_train']} "
            f"({payload['test_rows_in_train_label_conflict']} label-conflicting)",
            f"- Train duplicate groups: {payload['train_duplicate_groups']} "
            f"({payload['train_duplicate_excess_rows']} excess rows)",
            f"- Dev duplicate groups: {payload['dev_duplicate_groups']}",
            f"- Test duplicate groups: {payload['test_duplicate_groups']}",
            "",
            "## Cleaning policy (decision D3)",
            "",
            "Rows are sorted by numeric id and three stages run on train only:",
            "",
            "1. drop rows whose normalised text appears in dev or test;",
            "2. drop every row of a group whose normalised text carries more than one intent;",
            "3. keep the lowest-id row of every remaining duplicate group.",
            "",
            "Dev and test are never modified.",
            "",
            "## Dropped rows",
            "",
            "| reason | rows |",
            "|---|---|",
        ]
    )
    for reason, count in drops.items():
        lines.append(f"| {reason} | {count} |")
    lines.extend(
        [
            "",
            f"Train after cleaning: **{payload['train_after']}** rows.",
            "",
            "Translator `worker_id` cannot be used to regroup splits: "
            f"{workers['workers_in_multiple_partitions']} of "
            f"{workers['total_workers']} workers appear in more than one partition.",
            "",
        ]
    )
    return "\n".join(lines)


def write_data_audit(inspection: DatasetInspection, out_dir: Path) -> DataAuditPaths:
    """Write ``data_audit.json`` and ``data_audit.md`` under ``out_dir``."""
    target = Path(out_dir)
    target.mkdir(parents=True, exist_ok=True)
    payload = build_audit_payload(inspection)
    json_path = target / "data_audit.json"
    json_path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    markdown_path = target / "data_audit.md"
    markdown_path.write_text(render_markdown(payload), encoding="utf-8")
    return DataAuditPaths(json_path=json_path, markdown_path=markdown_path)


class AuditDataUseCase:
    """Inspect the raw dataset and write the committed audit report."""

    def __init__(self, pipeline: PrepareDataPipeline, out_dir: Path) -> None:
        self._pipeline = pipeline
        self._out_dir = Path(out_dir)

    def run(self, *, force: bool = False) -> DataAuditPaths:
        """Fetch (or reuse cached) data, compute the audit and write both files."""
        return write_data_audit(self._pipeline.inspect(force=force), self._out_dir)
