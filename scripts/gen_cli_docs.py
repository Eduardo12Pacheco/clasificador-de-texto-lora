#!/usr/bin/env python
"""Generate ``docs/CLI.md`` from the live Typer application (S13)."""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

import typer.main
from typer._click.core import Command, Context

from stc.adapters.cli.app import app

EXIT_CODES = (
    (0, "Success."),
    (1, "Unexpected failure."),
    (2, "Usage error or invalid input."),
    (3, "Integrity, checksum or untrusted-artifact failure."),
    (4, "Artifact not found (the message names the fix command)."),
    (5, "Offline refusal (``STC_OFFLINE``)."),
    (6, "Test split locked (an audited ``--final`` run is required)."),
)


def _help_text(command: Command, context: Context) -> str:
    text = command.get_help(context)
    lines = [line.rstrip() for line in text.splitlines()]
    while lines and not lines[0]:
        lines.pop(0)
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines)


def _children(command: Command) -> list[Command]:
    children = getattr(command, "commands", None)
    if not isinstance(children, dict):
        return []
    return [children[name] for name in sorted(children)]


def _collect_help(
    command: Command,
    *,
    path: Sequence[str],
    parent: Context | None,
) -> list[tuple[tuple[str, ...], str]]:
    name = path[-1]
    context = Context(
        command,
        info_name=name,
        parent=parent,
        terminal_width=100,
        max_content_width=100,
    )
    entries = [(tuple(path), _help_text(command, context))]
    for child in _children(command):
        entries.extend(
            _collect_help(
                child,
                path=[*path, str(child.name)],
                parent=context,
            )
        )
    return entries


def _tree_lines(command: Command, prefix: str = "") -> list[str]:
    lines: list[str] = []
    children = _children(command)
    for index, child in enumerate(children):
        last = index == len(children) - 1
        connector = "└── " if last else "├── "
        lines.append(f"{prefix}{connector}{child.name}")
        extension = "    " if last else "│   "
        lines.extend(_tree_lines(child, prefix + extension))
    return lines


def build_cli_docs() -> str:
    """Return the deterministic Markdown reference for the whole CLI."""
    root = typer.main.get_command(app)
    if not _children(root):
        raise TypeError("the Typer application is not a command group")
    entries = _collect_help(root, path=["stc"], parent=None)

    blocks: list[str] = [
        "# CLI reference",
        "",
        "Generated by `scripts/gen_cli_docs.py` from the live Typer application. "
        "Do not edit this file by hand.",
        "",
        "## Command tree",
        "",
        "```text",
        "stc",
        *_tree_lines(root),
        "```",
        "",
        "## Exit codes",
        "",
        "| Code | Meaning |",
        "|---|---|",
        *[f"| {code} | {meaning} |" for code, meaning in EXIT_CODES],
        "",
    ]
    for path, help_text in entries:
        title = " ".join(path)
        blocks.extend([f"## `{title}`", "", "```text", help_text, "```", ""])
    return "\n".join(blocks).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write ``docs/CLI.md`` or check that it is current."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("docs/CLI.md"))
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail when the committed file differs from the generated document.",
    )
    args = parser.parse_args(argv)
    try:
        generated = build_cli_docs()
    except (OSError, TypeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    if args.check:
        if not args.out.is_file():
            print(f"error: missing {args.out}", file=sys.stderr)
            return 1
        if args.out.read_text(encoding="utf-8") != generated:
            print(f"error: {args.out} is out of date; run scripts/gen_cli_docs.py", file=sys.stderr)
            return 1
        print(f"OK: {args.out} is current")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(generated, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
